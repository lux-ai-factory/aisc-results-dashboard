def psql(sql, *, db="platform", user=SUPER, check=True):
    assert CONTAINER.startswith("aisc-t-"), "refusing: not a throwaway container"
    out = subprocess.run(
        ["docker", "exec", "-i", CONTAINER, "psql", "-X", "-q", "-At", "-F", "|",
         "-v", "ON_ERROR_STOP=1", "-U", user, "-d", db],
        input=sql, text=True, capture_output=True)
    if check and out.returncode != 0:
        raise AssertionError(f"psql as {user} on {db} failed:\n{out.stderr}")
    return out


