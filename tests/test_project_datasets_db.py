class Seeded:
    """The prepared DBs, and what could not be prepared because the feature it
    needs is not built yet. A test that needs a part fails with that reason
    instead of erroring in the fixture."""

    def __init__(self):
        self.db = f"project_{P_HEX}"
        self.q_db = f"project_{Q.replace('-', '')}"
        self.r_db = f"project_{R.replace('-', '')}"
        self.missing = {}

    def need(self, *parts):
        for part in parts:
            if part in self.missing:
                pytest.fail(f"not built yet ({part}): {self.missing[part]}")


